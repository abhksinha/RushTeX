#!/usr/bin/env python3
"""gen_tfm.py <out.rs>: writes every Computer Modern / AMS TFM that RushTeX uses as a `Tfm`
static in the TFM file's own layout (tex.web §539-§545): one raw char_info word per code
(width, height, depth and italic indices, tag, remainder) indexing the font's small tables of
distinct fix_words (2^-20 of the design size), plus the lig/kern program (raw words, §545),
the kerns, the extensible recipes and fontdimens.
Exact to the fix_word, and 4 bytes per character. Needs kpsewhich on PATH.
"""
import struct, subprocess, sys

FONTS = """cmr5 cmr6 cmr7 cmr8 cmr9 cmr10 cmr12 cmr17
cmmi5 cmmi6 cmmi7 cmmi8 cmmi9 cmmi10 cmmi12 cmmib5 cmmib7 cmmib10
cmsy5 cmsy6 cmsy7 cmsy8 cmsy9 cmsy10 cmbsy5 cmbsy7 cmbsy10 cmex7 cmex8 cmex9 cmex10
cmbx5 cmbx6 cmbx7 cmbx8 cmbx9 cmbx10 cmbx12 cmti7 cmti8 cmti9 cmti10 cmti12
cmsl10 cmcsc10 cmtt8 cmtt9 cmtt10 cmtt12 cmss8 cmss10 cmssbx10
msam10 msbm10 eufm5 eufm7 eufm10""".split()


def tfm(name):
    path = subprocess.check_output(["kpsewhich", name + ".tfm"]).decode().strip()
    d = open(path, "rb").read()
    lf, lh, bc, ec, nw, nh, nd, ni, nl, nk, ne, np_ = struct.unpack(">12H", d[:24])
    words = lambda off, n: list(struct.unpack(f">{n}i", d[off:off + 4 * n]))
    design = words(24 + 4, 1)[0]
    ci = 24 + lh * 4
    info = [0] * 128
    for c in range(bc, ec + 1):
        assert c < 128, (name, c)
        info[c] = struct.unpack(">I", d[ci + 4 * (c - bc): ci + 4 * (c - bc) + 4])[0]
    off = ci + (ec - bc + 1) * 4
    w = words(off, nw); off += 4 * nw
    h = words(off, nh); off += 4 * nh
    dp = words(off, nd); off += 4 * nd
    it = words(off, ni); off += 4 * ni
    lig_kern = [struct.unpack(">I", d[off + 4 * i: off + 4 * i + 4])[0] for i in range(nl)]; off += 4 * nl
    kerns = words(off, nk); off += 4 * nk
    exten = [tuple(d[off + 4 * i: off + 4 * i + 4]) for i in range(ne)]; off += 4 * ne
    params = words(off, np_)
    return design, info, w, h, dp, it, exten, params, lig_kern, kerns


out = ["// Generated by scripts/fontgen/gen_tfm.py from the TeX Live .tfm files. Do not edit by hand.",
       "use crate::backend::backend_tfm::Tfm;", ""]
for name in FONTS:
    design, info, w, h, dp, it, exten, params, lig_kern, kerns = tfm(name)
    N = name.upper()
    out.append(f"pub static {N}_TFM: Tfm = Tfm {{")
    out.append(f"    design: {design},")
    out.append("    info: [" + ", ".join(f"0x{x:08X}" for x in info) + "],")
    for field, xs in (("widths", w), ("heights", h), ("depths", dp), ("italics", it), ("params", params)):
        out.append(f"    {field}: &[" + ", ".join(map(str, xs)) + "],")
    out.append("    lig_kern: &[" + ", ".join(f"0x{x:08X}" for x in lig_kern) + "],")
    out.append("    kerns: &[" + ", ".join(map(str, kerns)) + "],")
    out.append("    exten: &[" + ", ".join(f"[{a}, {b}, {c}, {e}]" for a, b, c, e in exten) + "],")
    out.append("};")
    out.append("")
open(sys.argv[1], "w").write("\n".join(out))
