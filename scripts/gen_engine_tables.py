#!/usr/bin/env python3
"""Generate src/engine/engine_tables.rs from pdfTeX's sources.

The engine's parameter table (every `assign_int`, `assign_dimen`, `assign_glue`,
`assign_mu_glue` and `assign_toks` primitive of pdftex.web) and its table of every primitive
name with its command code (tex.web §209's `cur_cmd`), so a primitive the engine does not run
itself still has a meaning. TeX's own parameters keep tex.web's code numbers (the engine's
existing slots); e-TeX and pdfTeX parameters follow in pdftex.web's order.

Usage: scripts/gen_engine_tables.py   (rewrites src/engine/engine_tables.rs)
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
W2C = ROOT / "texlive-source/texk/web2c"
# pdftex.web and the change files pdfTeX is built with (pdftexdir/am/pdftex.am's
# `pdftex_ch_srcs`, without encTeX, which pdflatex does not enable), plus SyncTeX.
CHANGES = ["tex.ch", "tracingstacklevels.ch", "partoken-102.ch", "partoken.ch", "showstream.ch",
           "pdftexdir/pdftex.ch", "synctexdir/synctex-p-rec.ch0"]
WEB = "\n".join((W2C / f).read_text(encoding="latin-1") for f in ["pdftexdir/pdftex.web"] + CHANGES if (W2C / f).exists())
OUT = ROOT / "src/engine/engine_tables.rs"

# tex.web's code numbers: §236 integers, §247 dimensions, §224 glue (mu glue 15-17).
TEX_INT = """pretolerance tolerance linepenalty hyphenpenalty exhyphenpenalty clubpenalty widowpenalty
displaywidowpenalty brokenpenalty binoppenalty relpenalty predisplaypenalty postdisplaypenalty
interlinepenalty doublehyphendemerits finalhyphendemerits adjdemerits mag delimiterfactor looseness
time day month year showboxbreadth showboxdepth hbadness vbadness pausing tracingonline
tracingmacros tracingstats tracingparagraphs tracingpages tracingoutput tracinglostchars
tracingcommands tracingrestores uchyph outputpenalty maxdeadcycles hangafter floatingpenalty
globaldefs fam escapechar defaulthyphenchar defaultskewchar endlinechar newlinechar language
lefthyphenmin righthyphenmin holdinginserts errorcontextlines""".split()
TEX_DIMEN = """parindent mathsurround lineskiplimit hsize vsize maxdepth splitmaxdepth boxmaxdepth hfuzz
vfuzz delimitershortfall nulldelimiterspace scriptspace predisplaysize displaywidth displayindent
overfullrule hangindent hoffset voffset emergencystretch""".split()
TEX_GLUE = """lineskip baselineskip parskip abovedisplayskip belowdisplayskip abovedisplayshortskip
belowdisplayshortskip leftskip rightskip topskip splittopskip tabskip spaceskip xspaceskip
parfillskip thinmuskip medmuskip thickmuskip""".split()
TEX_TOKS = "output everypar everymath everydisplay everyhbox everyvbox everyjob everycr errhelp".split()

# `primitive("name",cmd,...)`, the command possibly on the next line; one-character names
# (`\ `, `\/`, `\-`) included.
prims = re.findall(r'primitive\("([^"]+)",\s*(?:@\|)?\s*([a-z_]+)', WEB)
# MLTeX's primitives exist only in formats built with `-mltex`; pdflatex is not.
MLTEX = {"charsubdef", "tracingcharsubdef", "charsubdefmin", "charsubdefmax"}
prims = [(n, c) for n, c in prims if n not in MLTEX]
seen = {}
for name, cmd in prims:
    seen.setdefault(name, cmd)

def params(cmds, base):
    order = list(base)
    for name, cmd in prims:
        if cmd in cmds and name not in order:
            order.append(name)
    return order

ints = params({"assign_int"}, TEX_INT)
dimens = params({"assign_dimen"}, TEX_DIMEN)
glues = params({"assign_glue", "assign_mu_glue"}, TEX_GLUE)
toks = params({"assign_toks"}, TEX_TOKS)

rows = [(n, "Int", i) for i, n in enumerate(ints)] + [(n, "Dimen", i) for i, n in enumerate(dimens)] \
    + [(n, "Glue", i) for i, n in enumerate(glues)] + [(n, "Toks", i) for i, n in enumerate(toks)]
rows.sort()
param_names = {r[0] for r in rows}

cmds = sorted({c for c in seen.values()})
def camel(c):
    return "".join(p.capitalize() for p in c.split("_"))
native = sorted((n, c) for n, c in seen.items() if n not in param_names)

lines = [
    "//! Generated by `scripts/gen_engine_tables.py` from pdftex.web; do not edit by hand.",
    "//!",
    "//! The parameter table and every primitive's command code (§209).",
    "",
    "use super::engine_eqtb::Region;",
    "",
    f"pub const INT_PARAMS: u32 = {len(ints)};",
    f"pub const DIMEN_PARAMS: u32 = {len(dimens)};",
    f"pub const GLUE_PARAMS: u32 = {len(glues)};",
    f"pub const TOKS_PARAMS: u32 = {len(toks)};",
    "",
    "/// Parameters by name, sorted: (name, region, slot).",
    f"pub static PARAMS: [(&str, Region, u16); {len(rows)}] = [",
]
lines += [f'    ("{n}", Region::{r}, {i}),' for n, r, i in rows]
lines += [
    "];",
    "",
    "/// tex.web §207–§210's command codes, by name.",
    "#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]",
    "#[allow(clippy::enum_variant_names)]",
    "pub enum Cmd {",
]
lines += [f"    {camel(c)}," for c in cmds]
lines += [
    "}",
    "",
    "/// Every primitive that is not a parameter, sorted: (name, command code).",
    f"pub static PRIMITIVES: [(&str, Cmd); {len(native)}] = [",
]
lines += [f'    ("{n}", Cmd::{camel(c)}),' for n, c in native]
lines += ["];", ""]
OUT.write_text("\n".join(lines))
print(f"{OUT.relative_to(ROOT)}: {len(rows)} parameters, {len(native)} primitives, {len(cmds)} commands")
