//! 128-bit content hashing: the content ids of the generated tables and font packs, so a
//! table is known by what it holds. Two independent 64-bit lanes, each mixed with a folded
//! 64×64→128 multiply (as wyhash does), make an accidental collision between two different
//! paragraphs or pages about as likely as a 2^-128 event. It is not meant to resist inputs
//! crafted to collide.

const K_A: u64 = 0xa076_1d64_78bd_642f;
const K_B: u64 = 0xe703_7ed1_a0b4_28db;
const K_C: u64 = 0x8ebc_6af0_9c88_c6e3;

#[inline(always)]
fn fold_mul(a: u64, b: u64) -> u64 {
    let m = (a as u128).wrapping_mul(b as u128);
    (m as u64) ^ ((m >> 64) as u64)
}

/// One 64-bit lane of the same folded multiply over `bytes`, keyed by `seed`: the hash of
/// the static tables' perfect hashes (`data_phf`). Fixed by this code, not by the Rust
/// version, so tables generated by one build are read by another on any target.
#[inline]
pub fn hash64(seed: u64, bytes: &[u8]) -> u64 {
    let mut h = seed ^ K_A ^ (bytes.len() as u64).wrapping_mul(K_C);
    let (chunks, rest) = bytes.as_chunks::<8>();
    for &c in chunks {
        h = fold_mul(h ^ u64::from_le_bytes(c), K_B);
    }
    let mut tail = [0u8; 8];
    tail[..rest.len()].copy_from_slice(rest);
    fold_mul(h ^ u64::from_le_bytes(tail), K_C) ^ h.rotate_left(29)
}

/// The folded 64×64→128 multiply, for mixing a hash with a further key (`data_phf` pilots).
#[inline(always)]
pub fn mix64(a: u64, b: u64) -> u64 {
    fold_mul(a ^ K_A, b ^ K_B)
}

/// Streaming 128-bit hash of a sequence of words and byte strings.
#[derive(Clone, Copy)]
pub struct ContentHasher {
    a: u64,
    b: u64,
}

impl Default for ContentHasher {
    fn default() -> Self {
        Self::new()
    }
}

impl ContentHasher {
    #[inline]
    pub const fn new() -> Self {
        Self { a: K_A, b: K_B }
    }

    #[inline(always)]
    pub fn u64(&mut self, v: u64) {
        self.a = fold_mul(self.a ^ v, K_B);
        self.b = fold_mul(self.b ^ v.rotate_left(32), K_C);
    }

    #[inline(always)]
    pub fn u32(&mut self, v: u32) {
        self.u64(v as u64);
    }

    /// Hashes `bytes` with their length, so consecutive strings cannot run together.
    #[inline]
    pub fn bytes(&mut self, bytes: &[u8]) {
        let (chunks, rest) = bytes.as_chunks::<8>();
        for &c in chunks {
            self.u64(u64::from_le_bytes(c));
        }
        let mut tail = [0u8; 8];
        tail[..rest.len()].copy_from_slice(rest);
        self.u64(u64::from_le_bytes(tail) ^ ((bytes.len() as u64) << 56));
        self.u64(bytes.len() as u64);
    }

    #[inline]
    pub fn finish(self) -> u128 {
        let a = fold_mul(self.a ^ K_C, self.b ^ K_A);
        let b = fold_mul(self.b ^ K_B, self.a.rotate_left(17) ^ K_C);
        ((a as u128) << 64) | b as u128
    }
}

/// SHA-256 (FIPS 180-4) of `data`: the digest a font pack's file is pinned by in the binary
/// (`data_pack`), checked before a downloaded or copied pack is installed. Not on any hot
/// path; a pack is hashed once, when it is installed.
pub fn sha256(data: &[u8]) -> [u8; 32] {
    const K: [u32; 64] = [
        0x428a2f98, 0x71374491, 0xb5c0fbcf, 0xe9b5dba5, 0x3956c25b, 0x59f111f1, 0x923f82a4, 0xab1c5ed5, 0xd807aa98, 0x12835b01, 0x243185be, 0x550c7dc3, 0x72be5d74, 0x80deb1fe, 0x9bdc06a7, 0xc19bf174, 0xe49b69c1, 0xefbe4786, 0x0fc19dc6, 0x240ca1cc, 0x2de92c6f, 0x4a7484aa, 0x5cb0a9dc, 0x76f988da, 0x983e5152, 0xa831c66d, 0xb00327c8, 0xbf597fc7, 0xc6e00bf3, 0xd5a79147, 0x06ca6351, 0x14292967,
        0x27b70a85, 0x2e1b2138, 0x4d2c6dfc, 0x53380d13, 0x650a7354, 0x766a0abb, 0x81c2c92e, 0x92722c85, 0xa2bfe8a1, 0xa81a664b, 0xc24b8b70, 0xc76c51a3, 0xd192e819, 0xd6990624, 0xf40e3585, 0x106aa070, 0x19a4c116, 0x1e376c08, 0x2748774c, 0x34b0bcb5, 0x391c0cb3, 0x4ed8aa4a, 0x5b9cca4f, 0x682e6ff3, 0x748f82ee, 0x78a5636f, 0x84c87814, 0x8cc70208, 0x90befffa, 0xa4506ceb, 0xbef9a3f7, 0xc67178f2,
    ];
    let mut h: [u32; 8] = [0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19];
    // The message, a 1 bit, zeros to 56 bytes modulo 64, its length in bits (big-endian).
    let mut tail = data[data.len() / 64 * 64..].to_vec();
    tail.push(0x80);
    while tail.len() % 64 != 56 {
        tail.push(0);
    }
    tail.extend_from_slice(&((data.len() as u64).wrapping_mul(8)).to_be_bytes());
    for block in data.as_chunks::<64>().0.iter().chain(tail.as_chunks::<64>().0) {
        let mut w = [0u32; 64];
        for (i, c) in block.as_chunks::<4>().0.iter().enumerate() {
            w[i] = u32::from_be_bytes(*c);
        }
        for i in 16..64 {
            let s0 = w[i - 15].rotate_right(7) ^ w[i - 15].rotate_right(18) ^ (w[i - 15] >> 3);
            let s1 = w[i - 2].rotate_right(17) ^ w[i - 2].rotate_right(19) ^ (w[i - 2] >> 10);
            w[i] = w[i - 16].wrapping_add(s0).wrapping_add(w[i - 7]).wrapping_add(s1);
        }
        let [mut a, mut b, mut c, mut d, mut e, mut f, mut g, mut hh] = h;
        for i in 0..64 {
            let s1 = e.rotate_right(6) ^ e.rotate_right(11) ^ e.rotate_right(25);
            let ch = (e & f) ^ (!e & g);
            let t1 = hh.wrapping_add(s1).wrapping_add(ch).wrapping_add(K[i]).wrapping_add(w[i]);
            let s0 = a.rotate_right(2) ^ a.rotate_right(13) ^ a.rotate_right(22);
            let maj = (a & b) ^ (a & c) ^ (b & c);
            let t2 = s0.wrapping_add(maj);
            (hh, g, f, e, d, c, b, a) = (g, f, e, d.wrapping_add(t1), c, b, a, t1.wrapping_add(t2));
        }
        for (x, y) in h.iter_mut().zip([a, b, c, d, e, f, g, hh]) {
            *x = x.wrapping_add(y);
        }
    }
    let mut out = [0u8; 32];
    for (i, x) in h.iter().enumerate() {
        out[4 * i..4 * i + 4].copy_from_slice(&x.to_be_bytes());
    }
    out
}

/// A digest as lowercase hexadecimal, as `sha256sum` prints it.
pub fn hex(digest: &[u8]) -> String {
    digest.iter().map(|b| format!("{b:02x}")).collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    /// FIPS 180-4's examples, and a message across a block boundary (`sha256sum`'s digest).
    #[test]
    fn sha256_matches_the_standard() {
        assert_eq!(hex(&sha256(b"")), "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855");
        assert_eq!(hex(&sha256(b"abc")), "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad");
        assert_eq!(hex(&sha256(b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq")), "248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1");
        assert_eq!(hex(&sha256(&[b'a'; 1000])), "41edece42d63e8d9bf515a9ba6932e1c20cbc9f5a5d134645adb5db1b9737ea3");
    }

    #[test]
    fn strings_do_not_run_together() {
        let mut a = ContentHasher::new();
        a.bytes(b"ab");
        a.bytes(b"c");
        let mut b = ContentHasher::new();
        b.bytes(b"a");
        b.bytes(b"bc");
        assert_ne!(a.finish(), b.finish());
    }
}
