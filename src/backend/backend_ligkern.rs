//! TeX ligature/kern programs of the Computer Modern fonts RushTeX typesets with.
//!
//! Generated from the `.tfm` files of TeX Live. Kerns are in 1/10000 em; ligatures keep
//! TFM's operation code (0 is `=:`, the only kind CM text fonts use for letters) and the
//! resulting character. Pairs are keyed `left << 8 | right` and sorted for binary search.

#![forbid(unsafe_code)]

/// Kerns and ligatures of one font.
///
/// Besides the sorted pair lists, the table carries a per-left-character index (built at
/// compile time) so a lookup only searches the handful of pairs sharing the left glyph, the
/// way TFM's `char_info` points each character at its own lig/kern program.
pub struct LigKernTable {
    pub kerns: &'static [(u16, i16)],
    pub ligs: &'static [(u16, u8, u8)],
    /// `kerns[kern_start[c]..kern_start[c + 1]]` are the kerns whose left glyph is `c`.
    kern_start: [u16; 257],
    /// Bitmap of left glyphs that start at least one ligature.
    lig_left: [u64; 4],
    /// For left glyphs below 128: bitmap of right glyphs below 128 it kerns with, so the
    /// common no-kern pair costs one bit test (2 KiB per font, L1-resident).
    kern_right: [[u64; 2]; 128],
}

impl LigKernTable {
    /// Builds the table and its per-left-glyph index; `kerns` and `ligs` must be sorted by key.
    pub const fn new(kerns: &'static [(u16, i16)], ligs: &'static [(u16, u8, u8)]) -> Self {
        let mut kern_start = [0u16; 257];
        let mut i = 0;
        let mut c = 0usize;
        while c < 256 {
            while i < kerns.len() && ((kerns[i].0 >> 8) as usize) < c {
                i += 1;
            }
            kern_start[c] = i as u16;
            c += 1;
        }
        kern_start[256] = kerns.len() as u16;
        let mut kern_right = [[0u64; 2]; 128];
        let mut k = 0;
        while k < kerns.len() {
            let l = (kerns[k].0 >> 8) as usize;
            let r = (kerns[k].0 & 0xFF) as usize;
            if l < 128 && r < 128 {
                kern_right[l][r >> 6] |= 1u64 << (r & 63);
            }
            k += 1;
        }
        let mut lig_left = [0u64; 4];
        let mut j = 0;
        while j < ligs.len() {
            let l = (ligs[j].0 >> 8) as usize;
            lig_left[l >> 6] |= 1u64 << (l & 63);
            j += 1;
        }
        LigKernTable {
            kerns,
            ligs,
            kern_start,
            lig_left,
            kern_right,
        }
    }

    /// Kern between two characters, in 1/10000 em.
    #[inline]
    pub fn kern_units(&self, left: u8, right: u8) -> i32 {
        if left < 128 && right < 128 {
            let bits = self.kern_right[left as usize][(right >> 6) as usize];
            if bits & (1u64 << (right & 63)) == 0 {
                return 0;
            }
        }
        let lo = self.kern_start[left as usize] as usize;
        let hi = self.kern_start[left as usize + 1] as usize;
        if lo == hi {
            return 0;
        }
        let key = (left as u16) << 8 | right as u16;
        match self.kerns[lo..hi].binary_search_by_key(&key, |e| e.0) {
            Ok(i) => self.kerns[lo + i].1 as i32,
            Err(_) => 0,
        }
    }

    /// Kern between two characters, in em.
    #[inline]
    pub fn kern(&self, left: u8, right: u8) -> f32 {
        self.kern_units(left, right) as f32 * 1e-4
    }

    /// Ligature formed by two characters, as `(operation, character)`.
    #[inline]
    pub fn lig(&self, left: u8, right: u8) -> Option<(u8, u8)> {
        if self.lig_left[(left >> 6) as usize] & (1u64 << (left & 63)) == 0 {
            return None;
        }
        let key = (left as u16) << 8 | right as u16;
        self.ligs
            .binary_search_by_key(&key, |e| e.0)
            .ok()
            .map(|i| (self.ligs[i].1, self.ligs[i].2))
    }
}

