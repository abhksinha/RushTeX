/// A macro: its parameter text, `end_match`, and body, as one list (§389), and its prefixes.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Macro {
    pub text: Span,
    pub flags: u8,
}

/// What a control sequence or active character means (§222 `eq_type` and `equiv`).
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum Meaning {
    /// Never assigned: the primitive or parameter of that name, if there is one, else
    /// undefined.
    #[default]
    Unset,
    /// Assigned undefined (`\let\x\undefined`).
    Undefined,
    Prim(Prim),
    Macro(Macro),
    /// `\let\x=a`: a character token.
    Char(Token),
    /// A parameter or register: `\tolerance`, or `\countdef\x=5` (§1224 `assign_int`
    /// and its kin).
    Reg(Reg),
    /// `\chardef` (§1224 `char_given`) and `\mathchardef` (`math_given`).
    CharDef(u32),
    MathCharDef(u32),
    /// §358: an expandable token read after `\noexpand`; it acts as `\relax` (with TeX's
    /// `no_expand_flag`, so `\ifx` tells it from `\relax`).
    DontExpand,
    /// A font identifier (§1257 `set_font`): its index in the engine's font list.
    Font(u16),
    /// A primitive the engine leaves to the native pipeline: its index in the generated
    /// `PRIMITIVES` table, whose command code says what operands it takes.
    Native(u16),
    /// A LaTeX command written natively (`crate::kernel`, the port's strangler step): its
    /// index in `kernel::KERNEL`. Bound per run by `RT_NATIVE` in place of the macro, which
    /// it calls for any case it does not take itself; unexpandable, like a primitive.
    Kernel(u16),
    /// A LaTeX command of the native document job (`engine_doc`): its index in
    /// `engine_doc::DOC`. Never in a format.
    Doc(u16),
}

#[cfg(test)]
