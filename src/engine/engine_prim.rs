/// The index of primitive `name` in the generated table of every primitive.
pub fn native(name: &str) -> Option<u16> {
    super::engine_tables::PRIMITIVES.binary_search_by(|p| p.0.cmp(name)).ok().map(|i| i as u16)
}

/// What a primitive or parameter name means before anything assigns it: a primitive the
/// engine runs, a parameter, or one it leaves to the native pipeline (§226's `primitive`
/// calls, which IniTeX makes once).
pub fn builtin(name: &str) -> Meaning {
    match prim(name) {
        // §553: `\nullfont` is a font identifier, not a command.
        Some(Prim::NullFont) => Meaning::Font(0),
        Some(p) => Meaning::Prim(p),
        None => match super::engine_names::param(name) {
            Some(r) => Meaning::Reg(r),
            None => native(name).map_or(Meaning::Undefined, Meaning::Native),
        },
    }
}

/// Every name the engine knows before a format runs: its own primitives, the parameters,
/// and pdfTeX's other primitives.
pub fn builtin_names() -> impl Iterator<Item = &'static str> {
    PRIMS.iter().map(|p| p.0).chain(super::engine_names::PARAMS.iter().map(|p| p.0)).chain(super::engine_tables::PRIMITIVES.iter().map(|p| p.0))
}

/// The primitive named `name`, if the engine runs it.
pub fn prim(name: &str) -> Option<Prim> {
    PRIMS.binary_search_by(|p| p.0.cmp(name)).ok().map(|i| PRIMS[i].1)
}

/// §489 `fi_code`, `else_code`, `or_code`, and `if_code` (the limit while a condition is
/// being evaluated): an `\else` or `\or` beyond the current limit is extra.
pub const IF_CODE: u8 = 1;
pub const FI_CODE: u8 = 2;
pub const ELSE_CODE: u8 = 3;
pub const OR_CODE: u8 = 4;

impl Prim {
    /// §366: whether the primitive acts during expansion (rather than in the main loop).
    pub const fn expandable(self) -> bool {
        matches!(self, Prim::TopMark | Prim::FirstMark | Prim::BotMark | Prim::SplitFirstMark | Prim::SplitBotMark | Prim::TopMarks | Prim::FirstMarks | Prim::BotMarks | Prim::SplitFirstMarks | Prim::SplitBotMarks | Prim::FontName | Prim::Meaning | Prim::Detokenize | Prim::Expanded | Prim::ETeXRevision | Prim::PdfStrcmp | Prim::Unexpanded | Prim::Input | Prim::ScanTokens | Prim::EndInput | Prim::JobName | Prim::Csname | Prim::ExpandAfter | Prim::NoExpand | Prim::String | Prim::Number | Prim::RomanNumeral | Prim::The | Prim::Unless | Prim::Else | Prim::Fi | Prim::Or) || self.is_if()
    }

    /// §487 `if_test`.
    pub const fn is_if(self) -> bool {
        matches!(
            self,
            Prim::If | Prim::IfCase | Prim::IfCat | Prim::IfCsname | Prim::IfDefined | Prim::IfDim | Prim::IfEof | Prim::IfFalse | Prim::IfHbox | Prim::IfHmode | Prim::IfInner | Prim::IfMmode | Prim::IfNum | Prim::IfOdd | Prim::IfTrue | Prim::IfVbox | Prim::IfVmode | Prim::IfVoid | Prim::IfX | Prim::IfPdfAbsNum | Prim::IfPdfAbsDim | Prim::IfFontChar | Prim::IfInCsname
        )
    }

    /// §489 `fi_or_else`: the code of `\fi`, `\else` or `\or`.
    pub const fn fi_or_else(self) -> Option<u8> {
        match self {
            Prim::Fi => Some(FI_CODE),
            Prim::Else => Some(ELSE_CODE),
            Prim::Or => Some(OR_CODE),
            _ => None,
        }
    }

    /// The primitive's name, for `\string` and messages.
    /// The primitive whose discriminant is `b` (a format stores primitives as bytes).
    pub fn from_u8(b: u8) -> Option<Prim> {
        PRIMS.iter().find(|p| p.1 as u8 == b).map(|p| p.1)
    }

    pub fn name(self) -> &'static str {
        PRIMS.iter().find(|p| p.1 == self).map_or("", |p| p.0)
    }
}

/// `\long`, `\outer` and `\protected` on a macro (§209 `long_call`, `outer_call`; e-TeX).
