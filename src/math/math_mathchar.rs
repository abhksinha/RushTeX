/// Looks up the TeX math code of a named math symbol.
#[inline]
pub fn lookup_mathchar(name: &str) -> Option<u16> {
    MATHCHAR_TABLE
        .binary_search_by(|(n, _)| n.as_bytes().cmp(name.as_bytes()))
        .ok()
        .map(|i| MATHCHAR_TABLE[i].1)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn mathchar_table_sorted_and_known_codes() {
        assert!(MATHCHAR_TABLE.windows(2).all(|w| w[0].0.as_bytes() < w[1].0.as_bytes()));
        assert_eq!(lookup_mathchar("ll"), Some(0x321C));
        assert_eq!(lookup_mathchar("alpha"), Some(0x010B));
        assert_eq!(lookup_mathchar("Gamma"), Some(0x7000));
        assert_eq!(lookup_mathchar("square"), Some(0x0403));
        assert_eq!(lookup_mathchar("nosuchsymbol"), None);
    }
}
