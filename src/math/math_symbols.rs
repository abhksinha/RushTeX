//! Centralized Declarative Mathematical Symbols and Metadata Table.
//!
//! Provides a single, maintainable compile-time `.rodata` catalog of all LaTeX
//! math commands, atom classes, Unicode codepoints, TFM dispatch codes,
//! and authoritative geometric bounding metrics.

#![forbid(unsafe_code)]

use crate::backend::fonts::Face;
use crate::math::math_spacing::MathAtomKind;

pub const FLAG_NONE: u8 = 0;
pub const FLAG_NEGATION: u8 = 1 << 0;
pub const FLAG_AXIS_CENTERED: u8 = 1 << 1;
pub const FLAG_VERTICAL_DOTS: u8 = 1 << 2;
pub const FLAG_DIAGONAL_DOTS: u8 = 1 << 3;
pub const FLAG_DELIMITER: u8 = 1 << 4;
pub const FLAG_LARGE_OP: u8 = 1 << 5;
pub const FLAG_INTEGRAL: u8 = 1 << 6;
pub const FLAG_RADICAL: u8 = 1 << 7;

/// A packed, static 48-byte record defining an individual mathematical symbol.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(C)]
pub struct MathSymbolRecord {
    pub cmd: &'static str,
    pub glyph: &'static str,
    pub unicode: u32,
    pub width_mu: u16,   // in milli-points (e.g. 7780 = 7.78 pt at 10pt base)
    pub height_mu: u16,  // in milli-points (e.g. 7300 = 7.30 pt at 10pt base)
    pub depth_mu: u16,   // in milli-points (e.g. 2300 = 2.30 pt at 10pt base)
    pub kind: MathAtomKind,
    pub face: Face,
    pub flags: u8,
    pub tfm_code: u8, // 0xFF denotes None
}

const _: () = assert!(core::mem::size_of::<MathSymbolRecord>() == 48);

impl MathSymbolRecord {
    #[inline(always)]
    pub const fn tfm_code_opt(&self) -> Option<u8> {
        if self.tfm_code == 0xFF {
            None
        } else {
            Some(self.tfm_code)
        }
    }

    #[inline(always)]
    pub fn width_pt(&self, font_size: f32) -> f32 {
        (self.width_mu as f32 * 0.001) * (font_size * 0.1)
    }

    #[inline(always)]
    pub fn height_pt(&self, font_size: f32) -> f32 {
        (self.height_mu as f32 * 0.001) * (font_size * 0.1)
    }

    #[inline(always)]
    pub fn depth_pt(&self, font_size: f32) -> f32 {
        (self.depth_mu as f32 * 0.001) * (font_size * 0.1)
    }

    #[inline(always)]
    pub const fn is_negation(&self) -> bool {
        (self.flags & FLAG_NEGATION) != 0
    }

    #[inline(always)]
    pub const fn is_axis_centered(&self) -> bool {
        (self.flags & FLAG_AXIS_CENTERED) != 0
    }

    #[inline(always)]
    pub const fn is_vertical_dots(&self) -> bool {
        (self.flags & FLAG_VERTICAL_DOTS) != 0
    }

    #[inline(always)]
    pub const fn is_diagonal_dots(&self) -> bool {
        (self.flags & FLAG_DIAGONAL_DOTS) != 0
    }

    #[inline(always)]
    pub const fn is_delimiter(&self) -> bool {
        (self.flags & FLAG_DELIMITER) != 0
    }

    #[inline(always)]
    pub const fn is_large_op(&self) -> bool {
        (self.flags & FLAG_LARGE_OP) != 0
    }

    #[inline(always)]
    pub const fn is_integral(&self) -> bool {
        (self.flags & FLAG_INTEGRAL) != 0
    }
}

