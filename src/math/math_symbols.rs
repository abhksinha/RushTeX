/// 256-byte 64-byte aligned prefix bucket table for O(1) symbol subslice range narrowing.
#[repr(C, align(64))]
pub struct SymbolBucketTable(pub [(u8, u8); 128]);

const fn build_initial_byte_buckets() -> SymbolBucketTable {
    let mut buckets = [(0u8, 0u8); 128];
    let n = MATH_SYMBOLS_TABLE.len();
    let mut i = 0;
    while i < n {
        let b = MATH_SYMBOLS_TABLE[i].cmd.as_bytes()[0];
        let start = i as u8;
        let mut j = i + 1;
        while j < n && MATH_SYMBOLS_TABLE[j].cmd.as_bytes()[0] == b {
            j += 1;
        }
        let end = j as u8;
        buckets[b as usize] = (start, end);
        i = j;
    }
    SymbolBucketTable(buckets)
}

pub static SYMBOL_BUCKET_TABLE: SymbolBucketTable = build_initial_byte_buckets();

const _: () = assert!(core::mem::size_of::<SymbolBucketTable>() == 256);
const _: () = assert!(core::mem::align_of::<SymbolBucketTable>() == 64);

/// Accelerated O(1) prefix bucketing + local binary search in compile-time `.rodata`.
#[inline(always)]
pub fn lookup_symbol(cmd: &str) -> Option<&'static MathSymbolRecord> {
    let bytes = cmd.as_bytes();
    let first = match bytes.first() {
        Some(&b) => b,
        None => return None,
    };
    if (first as usize) < 128 {
        let (start, end) = SYMBOL_BUCKET_TABLE.0[first as usize];
        if start < end {
            let slice = &MATH_SYMBOLS_TABLE[start as usize..end as usize];
            return slice
                .binary_search_by_key(&cmd, |r| r.cmd)
                .ok()
                .map(|idx| &slice[idx]);
        }
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_symbol_table_invariants() {
        assert_eq!(core::mem::size_of::<MathSymbolRecord>(), 48);

        // Verify strictly sorted alphabetically
        for i in 0..MATH_SYMBOLS_TABLE.len() - 1 {
            assert!(
                MATH_SYMBOLS_TABLE[i].cmd < MATH_SYMBOLS_TABLE[i + 1].cmd,
                "Symbol table out of order: {} >= {}",
                MATH_SYMBOLS_TABLE[i].cmd,
                MATH_SYMBOLS_TABLE[i + 1].cmd
            );
        }

        // Verify key lookups
        assert!(lookup_symbol("alpha").is_some());
        assert!(lookup_symbol("neq").is_some());
        assert!(lookup_symbol("notin").is_some());
        assert!(lookup_symbol("cdots").is_some());
        assert!(lookup_symbol("vdots").is_some());
        assert!(lookup_symbol("ddots").is_some());
        assert!(lookup_symbol("mid").is_some());
        assert!(lookup_symbol("sum").is_some());
        assert!(lookup_symbol("iint").is_some());
        assert!(lookup_symbol("land").is_some());
        assert!(lookup_symbol("lor").is_some());
        assert!(lookup_symbol("setminus").is_some());
        assert!(lookup_symbol("nonexistent_command_xyz").is_none());

        // Exhaustive verification across all 184 symbols
        for rec in MATH_SYMBOLS_TABLE.iter() {
            let found = lookup_symbol(rec.cmd);
            assert_eq!(found, Some(rec), "Failed to resolve symbol {}", rec.cmd);
        }
    }
}
